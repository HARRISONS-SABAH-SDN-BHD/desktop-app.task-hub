// Precompile the fixed JSON Schema: the desktop webview needs no unsafe-eval.
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import fs from "node:fs/promises";
const schema = JSON.parse(
  await fs.readFile(
    new URL("../config/tasks.schema.json", import.meta.url),
    "utf8",
  ),
);
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true },
});
const validate = ajv.compile(schema);
const code = standaloneCode(ajv, validate).replace(
  /const (\w+) = require\("([^"]+)"\)\.default;/g,
  (_, name, module) =>
    `import runtime_${name} from "${module}.js"; const ${name} = typeof runtime_${name} === "function" ? runtime_${name} : runtime_${name}.default;`,
);
await fs.writeFile(
  new URL("../src/domain/task-config.validator.js", import.meta.url),
  "// Generated by npm run schema:generate. Edit config/tasks.schema.json instead.\n" +
    code,
);
